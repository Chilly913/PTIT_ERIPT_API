package db

import (
	"context"
	"database/sql"
	"fmt"
	"io"
	"log/slog"
	"net/url"
	"os"
	"testing"
	"testing/fstest"
	"time"
)

// TestMigrator runs against TEST_DATABASE_URL (skipped when unset). It uses a
// throwaway schema so it never touches the real schema_migrations table.
func TestMigrator(t *testing.T) {
	dsn := os.Getenv("TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("TEST_DATABASE_URL not set")
	}
	schema := fmt.Sprintf("migrate_test_%d", time.Now().UnixNano())
	admin, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer admin.Close()
	if _, err := admin.Exec("CREATE SCHEMA " + schema); err != nil {
		t.Fatal(err)
	}
	defer admin.Exec("DROP SCHEMA " + schema + " CASCADE")

	u, err := url.Parse(dsn)
	if err != nil {
		t.Fatal(err)
	}
	q := u.Query()
	q.Set("search_path", schema)
	u.RawQuery = q.Encode()

	fsys := fstest.MapFS{
		"000001_a.up.sql":   {Data: []byte("CREATE TABLE a (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);")},
		"000001_a.down.sql": {Data: []byte("DROP TABLE IF EXISTS a;")},
		"000002_b.up.sql":   {Data: []byte("CREATE TABLE b (id bigint PRIMARY KEY, a_id bigint REFERENCES a(id));")},
		"000002_b.down.sql": {Data: []byte("DROP TABLE IF EXISTS b;")},
	}
	m, err := NewMigrator(u.String(), fsys, slog.New(slog.NewTextHandler(io.Discard, nil)))
	if err != nil {
		t.Fatal(err)
	}
	defer m.Close()

	expect := func(want uint, wantOK bool) {
		t.Helper()
		v, dirty, ok, err := m.Version()
		if err != nil || dirty || ok != wantOK || v != want {
			t.Fatalf("version = %d dirty=%v ok=%v err=%v, want %d ok=%v", v, dirty, ok, err, want, wantOK)
		}
	}
	expect(0, false)
	if err := m.Up(); err != nil {
		t.Fatal(err)
	}
	expect(2, true)
	if err := m.Up(); err != nil { // no change is not an error
		t.Fatal(err)
	}
	if err := m.Steps(-1); err != nil {
		t.Fatal(err)
	}
	expect(1, true)
	if err := m.Down(); err != nil {
		t.Fatal(err)
	}
	expect(0, false)

	var n int
	ctx := context.Background()
	if err := admin.QueryRowContext(ctx, "SELECT count(*) FROM information_schema.tables WHERE table_schema = $1 AND table_name IN ('a','b')", schema).Scan(&n); err != nil {
		t.Fatal(err)
	}
	if n != 0 {
		t.Fatalf("tables left after down: %d", n)
	}
}
