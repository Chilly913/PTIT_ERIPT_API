-- ---------------------------------------------------------------------------
-- Tokens. All secrets are stored as SHA-256 digests (32 bytes); the plaintext is
-- only ever returned to the client once.
-- ---------------------------------------------------------------------------

CREATE TABLE access_tokens (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id      bigint      NOT NULL,
    token_hash   bytea       NOT NULL,
    name         text        NOT NULL DEFAULT 'auth-token',
    abilities    text[],                     -- NULL = all abilities
    last_used_at timestamptz,
    expires_at   timestamptz NOT NULL,
    revoked_at   timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_access_tokens PRIMARY KEY (id),
    CONSTRAINT uq_access_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_access_tokens_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_access_tokens_token_hash CHECK (octet_length(token_hash) = 32),
    CONSTRAINT ck_access_tokens_name CHECK (char_length(name) <= 255)
);
CREATE INDEX ix_access_tokens_user_id ON access_tokens (user_id);
CREATE INDEX ix_access_tokens_expires_at ON access_tokens (expires_at);

CREATE TABLE refresh_tokens (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id         bigint      NOT NULL,
    access_token_id bigint,                  -- access token issued together with this refresh token
    family_id       uuid        NOT NULL,    -- rotation chain; reuse of a rotated token revokes the family
    token_hash      bytea       NOT NULL,
    expires_at      timestamptz NOT NULL,
    rotated_at      timestamptz,             -- set when exchanged for a new pair
    revoked_at      timestamptz,
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id),
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_access_token_id FOREIGN KEY (access_token_id)
        REFERENCES access_tokens (id) ON DELETE SET NULL,
    CONSTRAINT ck_refresh_tokens_token_hash CHECK (octet_length(token_hash) = 32)
);
CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_access_token_id ON refresh_tokens (access_token_id);
CREATE INDEX ix_refresh_tokens_family_id ON refresh_tokens (family_id);
CREATE INDEX ix_refresh_tokens_expires_at ON refresh_tokens (expires_at);

-- One-time tokens sent by e-mail: password reset and e-mail verification.
CREATE TABLE user_action_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint      NOT NULL,
    purpose     text        NOT NULL,
    token_hash  bytea       NOT NULL,
    email       citext      NOT NULL,        -- address the link was sent to; token is void if users.email changed
    expires_at  timestamptz NOT NULL,
    consumed_at timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_action_tokens PRIMARY KEY (id),
    CONSTRAINT uq_user_action_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_user_action_tokens_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_action_tokens_purpose CHECK (purpose IN ('password_reset', 'email_verification')),
    CONSTRAINT ck_user_action_tokens_token_hash CHECK (octet_length(token_hash) = 32)
);
-- invalidate previous pending tokens / throttle re-sends per user+purpose
CREATE INDEX ix_user_action_tokens_user_id_purpose ON user_action_tokens (user_id, purpose, created_at DESC);
CREATE INDEX ix_user_action_tokens_expires_at ON user_action_tokens (expires_at);

