-- ---------------------------------------------------------------------------
-- Organisation master data
-- ---------------------------------------------------------------------------

CREATE TABLE institutions (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    code             citext      NOT NULL,
    name             text        NOT NULL,
    institution_type text        NOT NULL DEFAULT 'university',
    is_active        boolean     NOT NULL DEFAULT true,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_institutions PRIMARY KEY (id),
    CONSTRAINT uq_institutions_code UNIQUE (code),
    CONSTRAINT ck_institutions_institution_type CHECK (char_length(institution_type) <= 100)
);
CREATE TRIGGER trg_institutions_updated_at BEFORE UPDATE ON institutions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE units (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    institution_id bigint      NOT NULL,
    parent_id      bigint,
    code           citext      NOT NULL,
    name           text        NOT NULL,
    unit_type      text        NOT NULL,   -- free-form in the API (board, office, faculty, ...)
    level          smallint    NOT NULL DEFAULT 1,
    is_active      boolean     NOT NULL DEFAULT true,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_units PRIMARY KEY (id),
    CONSTRAINT uq_units_institution_id_code UNIQUE (institution_id, code),
    CONSTRAINT fk_units_institution_id FOREIGN KEY (institution_id)
        REFERENCES institutions (id) ON DELETE RESTRICT,
    CONSTRAINT fk_units_parent_id FOREIGN KEY (parent_id)
        REFERENCES units (id) ON DELETE SET NULL,
    CONSTRAINT ck_units_unit_type CHECK (char_length(unit_type) <= 100),
    CONSTRAINT ck_units_level CHECK (level >= 1),
    CONSTRAINT ck_units_parent_id CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX ix_units_parent_id ON units (parent_id);
CREATE TRIGGER trg_units_updated_at BEFORE UPDATE ON units
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE positions (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    code        citext      NOT NULL,
    name        text        NOT NULL,
    scope_level text        NOT NULL DEFAULT 'unit',
    description text,
    is_active   boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_positions PRIMARY KEY (id),
    CONSTRAINT uq_positions_code UNIQUE (code),
    CONSTRAINT ck_positions_scope_level CHECK (scope_level IN ('institution', 'unit', 'cohort'))
);
CREATE TRIGGER trg_positions_updated_at BEFORE UPDATE ON positions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- Users
-- ---------------------------------------------------------------------------

CREATE TABLE users (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    -- account
    email                   citext      NOT NULL,
    password_hash           text,                    -- NULL = password login disabled (OAuth-only account)
    email_verified_at       timestamptz,
    name                    text        NOT NULL,
    user_type               text        NOT NULL DEFAULT 'student',
    avatar_path             text,                    -- object key, or absolute https URL for external (Google) avatars
    face_image_path         text,                    -- object key of the proctoring reference photo
    bio                     text,
    -- organisation
    institution_id          bigint,
    unit_id                 bigint,
    staff_code              citext,
    -- student academic placement (FKs to 000004 tables are in 000090_deferred_fks_identity)
    student_code            citext,
    program_id              bigint,
    major_id                bigint,
    specialization_id       bigint,
    cohort_id               bigint,
    administrative_class_id bigint,
    advisor_id              bigint,
    study_status            text,
    -- personal profile
    phone                   text,
    id_card_number          text,
    gender                  text,
    date_of_birth           date,
    nationality             text        NOT NULL DEFAULT 'Việt Nam',
    hometown                text,
    permanent_address       text,
    -- admin "q" search: name / email / codes / phone in one trigram-indexed column
    search_text             text GENERATED ALWAYS AS (
        name || ' ' || email::text
        || ' ' || coalesce(student_code::text, '')
        || ' ' || coalesce(staff_code::text, '')
        || ' ' || coalesce(phone, '')
    ) STORED,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    -- soft delete: deleted users cannot log in and are hidden from listings; history rows keep their FK.
    -- email / codes stay reserved after deletion (unique constraints are not partial).
    deleted_at              timestamptz,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT uq_users_student_code UNIQUE (student_code),
    CONSTRAINT uq_users_staff_code UNIQUE (staff_code),
    CONSTRAINT uq_users_id_card_number UNIQUE (id_card_number),
    CONSTRAINT fk_users_institution_id FOREIGN KEY (institution_id)
        REFERENCES institutions (id) ON DELETE SET NULL,
    CONSTRAINT fk_users_unit_id FOREIGN KEY (unit_id)
        REFERENCES units (id) ON DELETE SET NULL,
    CONSTRAINT fk_users_advisor_id FOREIGN KEY (advisor_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_users_email CHECK (char_length(email::text) <= 255),
    CONSTRAINT ck_users_name CHECK (char_length(name) <= 255),
    CONSTRAINT ck_users_user_type CHECK (user_type IN ('student', 'instructor', 'staff', 'academic_manager', 'admin')),
    CONSTRAINT ck_users_bio CHECK (char_length(bio) <= 1000),
    CONSTRAINT ck_users_student_code CHECK (char_length(student_code::text) <= 50),
    CONSTRAINT ck_users_staff_code CHECK (char_length(staff_code::text) <= 50),
    CONSTRAINT ck_users_phone CHECK (char_length(phone) <= 32),
    CONSTRAINT ck_users_id_card_number CHECK (char_length(id_card_number) <= 20),
    CONSTRAINT ck_users_gender CHECK (gender IN ('male', 'female', 'other')),
    CONSTRAINT ck_users_nationality CHECK (char_length(nationality) <= 64),
    CONSTRAINT ck_users_study_status CHECK (study_status IN (
        'dang_hoc', 'bao_luu', 'tot_nghiep', 'thoi_hoc', 'dinh_chi', 'chua_dong_hoc_phi',
        'dang_cong_tac', 'nghi_phep', 'nghi_huu'))
);
CREATE INDEX ix_users_institution_id ON users (institution_id);
CREATE INDEX ix_users_unit_id ON users (unit_id);
CREATE INDEX ix_users_program_id ON users (program_id);
CREATE INDEX ix_users_major_id ON users (major_id);
CREATE INDEX ix_users_specialization_id ON users (specialization_id) WHERE specialization_id IS NOT NULL;
CREATE INDEX ix_users_cohort_id ON users (cohort_id);
CREATE INDEX ix_users_administrative_class_id ON users (administrative_class_id);
CREATE INDEX ix_users_advisor_id ON users (advisor_id) WHERE advisor_id IS NOT NULL;
CREATE INDEX ix_users_created_at ON users (created_at);
CREATE INDEX ix_users_active ON users (id) WHERE deleted_at IS NULL;
CREATE INDEX ix_users_search_text ON users USING gin (search_text gin_trgm_ops);
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Hot gamification counters split off `users` (updated on every login / point award;
-- keeps the wide users row stable and gives the leaderboard its own narrow index).
-- A missing row means all zeros; Go upserts with ON CONFLICT (user_id).
CREATE TABLE user_stats (
    user_id             bigint      NOT NULL,
    points_balance      bigint      NOT NULL DEFAULT 0,
    streak_days         integer     NOT NULL DEFAULT 0,
    last_login_date     date,
    streak_last_updated date,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_stats PRIMARY KEY (user_id),
    CONSTRAINT fk_user_stats_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_user_stats_points_balance CHECK (points_balance >= 0),
    CONSTRAINT ck_user_stats_streak_days CHECK (streak_days >= 0)
);
CREATE INDEX ix_user_stats_points_balance ON user_stats (points_balance DESC, user_id);
CREATE TRIGGER trg_user_stats_updated_at BEFORE UPDATE ON user_stats
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Staff positions inside units (drives unit-scoped data access, see ScopesByUnit).
CREATE TABLE user_assignments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id     bigint      NOT NULL,
    unit_id     bigint      NOT NULL,
    position_id bigint      NOT NULL,
    is_primary  boolean     NOT NULL DEFAULT false,
    start_date  date,
    end_date    date,
    status      text        NOT NULL DEFAULT 'active',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_assignments PRIMARY KEY (id),
    CONSTRAINT fk_user_assignments_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_assignments_unit_id FOREIGN KEY (unit_id)
        REFERENCES units (id) ON DELETE RESTRICT,
    CONSTRAINT fk_user_assignments_position_id FOREIGN KEY (position_id)
        REFERENCES positions (id) ON DELETE RESTRICT,
    CONSTRAINT ck_user_assignments_status CHECK (status IN ('active', 'inactive')),
    CONSTRAINT ck_user_assignments_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
-- Also serves "active unit ids of user X" (every unit-scoped admin query) as an index-only scan.
CREATE UNIQUE INDEX uq_user_assignments_user_id_unit_id_position_id_active
    ON user_assignments (user_id, unit_id, position_id) WHERE status = 'active';
CREATE INDEX ix_user_assignments_user_id ON user_assignments (user_id);
CREATE INDEX ix_user_assignments_unit_id ON user_assignments (unit_id);
CREATE INDEX ix_user_assignments_position_id ON user_assignments (position_id);
CREATE UNIQUE INDEX uq_user_assignments_user_id_primary
    ON user_assignments (user_id) WHERE is_primary AND status = 'active';
CREATE TRIGGER trg_user_assignments_updated_at BEFORE UPDATE ON user_assignments
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

