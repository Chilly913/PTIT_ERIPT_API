-- ---------------------------------------------------------------------------
-- lessons
-- Common columns + video columns (video is the dominant type and is also used by
-- 'live' recordings; the API returns video_* flat on the lesson). Other type-specific
-- data lives in 1:1 child tables (scorm_packages, virtual_classes, lesson_assignments,
-- quizzes [000005], offline_sessions) because each has its own CRUD endpoint and is
-- serialised as a nested object.
-- ---------------------------------------------------------------------------
CREATE TABLE lessons (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id        bigint      NOT NULL,
    section_id       bigint,
    title            text        NOT NULL,
    type             text        NOT NULL DEFAULT 'video',
    description      text,
    position         integer     NOT NULL DEFAULT 0,    -- legacy `order`
    duration_seconds integer     NOT NULL DEFAULT 0,    -- legacy `duration`
    is_preview       boolean     NOT NULL DEFAULT false,
    video_path       text,         -- object key; absolute http(s) URL tolerated (YouTube, external)
    video_size_bytes bigint,       -- legacy video_size varchar('194 MB')
    video_status     text        NOT NULL DEFAULT 'pending',
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_lessons_title CHECK (char_length(title) BETWEEN 1 AND 255),
    CONSTRAINT ck_lessons_type CHECK (type IN (
        'video', 'audio', 'file', 'page', 'document', 'quiz', 'assignment', 'forum', 'survey',
        'scorm', 'h5p', 'virtual_class', 'zoom', 'meet', 'live', 'offline')),
    CONSTRAINT ck_lessons_position CHECK (position >= 0),
    CONSTRAINT ck_lessons_duration_seconds CHECK (duration_seconds >= 0),
    CONSTRAINT ck_lessons_video_path CHECK (char_length(video_path) <= 2048),
    CONSTRAINT ck_lessons_video_size_bytes CHECK (video_size_bytes >= 0),
    CONSTRAINT ck_lessons_video_status CHECK (video_status IN ('pending', 'processing', 'ready', 'failed')),
    CONSTRAINT fk_lessons_course_id FOREIGN KEY (course_id)
        REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_lessons_section_id FOREIGN KEY (section_id, course_id)
        REFERENCES sections (id, course_id) ON DELETE CASCADE
);
CREATE INDEX ix_lessons_course_id_position ON lessons (course_id, position);
CREATE INDEX ix_lessons_section_id_position ON lessons (section_id, position);
CREATE TRIGGER trg_lessons_updated_at BEFORE UPDATE ON lessons
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

