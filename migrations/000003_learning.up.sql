-- 000003_learning
-- Catalog (categories, courses, skills, CLOs), course content (sections, lessons and
-- their 1:1 type-specific children), learner activity (enrollments, progress, notes,
-- SCORM runtime state, assignment submissions), community (reviews, Q&A, reactions).
-- user_assignments is owned by 000002_identity.
-- References (lower-numbered files): users (000002).
-- FKs to later files (programs, majors, terms, cohorts, class_sections,
-- certificate_templates, orders) live in 000090_deferred_fks_learning.

-- ---------------------------------------------------------------------------
-- learning_search_fold(text): accent/case folding for Vietnamese search.
-- Legacy search used MySQL utf8mb4_0900_ai_ci LIKE ("toan" matches "Toán").
-- Query as: learning_search_fold(col) LIKE '%' || learning_search_fold($1) || '%'
-- so the trigram expression indexes below are used. Built only on immutable
-- built-ins (no unaccent extension needed).
-- ---------------------------------------------------------------------------
CREATE FUNCTION learning_search_fold(text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT lower(translate(normalize($1, NFC),
        'àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđÀÁẠẢÃÂẦẤẬẨẪĂẰẮẶẲẴÈÉẸẺẼÊỀẾỆỂỄÌÍỊỈĨÒÓỌỎÕÔỒỐỘỔỖƠỜỚỢỞỠÙÚỤỦŨƯỪỨỰỬỮỲÝỴỶỸĐ',
        'aaaaaaaaaaaaaaaaaeeeeeeeeeeeiiiiiooooooooooooooooouuuuuuuuuuuyyyyydaaaaaaaaaaaaaaaaaeeeeeeeeeeeiiiiiooooooooooooooooouuuuuuuuuuuyyyyyd'))
$$;

-- ---------------------------------------------------------------------------
-- categories (self-referencing tree, max 3 levels used by the API)
-- ---------------------------------------------------------------------------
CREATE TABLE categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   bigint,
    name        text        NOT NULL,
    slug        text        NOT NULL,
    icon        text,                    -- icon name or object key
    sort_order  smallint    NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_categories_slug UNIQUE (slug),
    CONSTRAINT ck_categories_name CHECK (char_length(name) BETWEEN 1 AND 255),
    CONSTRAINT ck_categories_slug CHECK (char_length(slug) BETWEEN 1 AND 255),
    CONSTRAINT ck_categories_sort_order CHECK (sort_order >= 0),
    CONSTRAINT ck_categories_parent_id CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT fk_categories_parent_id FOREIGN KEY (parent_id)
        REFERENCES categories (id) ON DELETE SET NULL
);
CREATE INDEX ix_categories_parent_id_sort_order ON categories (parent_id, sort_order, name);
CREATE TRIGGER trg_categories_updated_at BEFORE UPDATE ON categories
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- courses
-- ---------------------------------------------------------------------------
CREATE TABLE courses (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id           bigint        NOT NULL,      -- legacy user_id
    category_id             bigint,
    program_id              bigint,                      -- FK deferred (programs, 000004)
    major_id                bigint,                      -- FK deferred (majors, 000004)
    certificate_template_id bigint,                      -- FK deferred (certificate_templates, 000006)
    title                   text          NOT NULL,
    slug                    text          NOT NULL,
    description             text,
    learning_outcomes       jsonb         NOT NULL DEFAULT '[]'::jsonb,  -- marketing bullets (array of strings)
    benefits                jsonb         NOT NULL DEFAULT '[]'::jsonb,
    requirements            jsonb         NOT NULL DEFAULT '[]'::jsonb,
    level                   text,
    thumbnail_path          text,          -- object key; absolute http(s) URL tolerated for external images
    trailer_url             text,          -- external video URL (YouTube)
    price                   numeric(14,2) NOT NULL DEFAULT 0,
    course_mode             text          NOT NULL DEFAULT 'extension',
    is_credit_bearing       boolean       NOT NULL DEFAULT false,
    credit_value            smallint,
    status                  text          NOT NULL DEFAULT 'draft',
    is_featured             boolean       NOT NULL DEFAULT false,
    reject_reason           text,
    published_at            timestamptz,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT uq_courses_slug UNIQUE (slug),
    CONSTRAINT ck_courses_title CHECK (char_length(title) BETWEEN 1 AND 255),
    CONSTRAINT ck_courses_slug CHECK (char_length(slug) BETWEEN 1 AND 255),
    CONSTRAINT ck_courses_learning_outcomes CHECK (jsonb_typeof(learning_outcomes) = 'array'),
    CONSTRAINT ck_courses_benefits CHECK (jsonb_typeof(benefits) = 'array'),
    CONSTRAINT ck_courses_requirements CHECK (jsonb_typeof(requirements) = 'array'),
    CONSTRAINT ck_courses_level CHECK (level IN ('beginner', 'intermediate', 'advanced')),
    CONSTRAINT ck_courses_trailer_url CHECK (char_length(trailer_url) <= 2048),
    CONSTRAINT ck_courses_price CHECK (price >= 0),
    CONSTRAINT ck_courses_course_mode CHECK (course_mode IN ('core', 'extension')),
    CONSTRAINT ck_courses_credit_value CHECK (credit_value > 0),
    CONSTRAINT ck_courses_status CHECK (status IN ('draft', 'pending_review', 'published', 'rejected', 'closed')),
    CONSTRAINT fk_courses_instructor_id FOREIGN KEY (instructor_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_courses_category_id FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE SET NULL
);
CREATE INDEX ix_courses_instructor_id_created_at ON courses (instructor_id, created_at DESC);
CREATE INDEX ix_courses_category_id ON courses (category_id);
CREATE INDEX ix_courses_program_id ON courses (program_id) WHERE program_id IS NOT NULL;
CREATE INDEX ix_courses_major_id ON courses (major_id) WHERE major_id IS NOT NULL;
CREATE INDEX ix_courses_certificate_template_id ON courses (certificate_template_id)
    WHERE certificate_template_id IS NOT NULL;
-- public catalog: status = 'published' ORDER BY is_featured DESC, created_at DESC
CREATE INDEX ix_courses_status_is_featured_created_at ON courses (status, is_featured DESC, created_at DESC);
CREATE INDEX ix_courses_course_mode_status ON courses (course_mode, status);
-- accent-insensitive LIKE search on title / description (CourseController@index, admin lists)
CREATE INDEX ix_courses_title_trgm ON courses USING gin (learning_search_fold(title) gin_trgm_ops);
CREATE INDEX ix_courses_description_trgm ON courses USING gin (learning_search_fold(description) gin_trgm_ops);
CREATE TRIGGER trg_courses_updated_at BEFORE UPDATE ON courses
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

