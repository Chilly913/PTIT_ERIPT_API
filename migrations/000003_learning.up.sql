-- Polymorphic (reactable_type, reactable_id) replaced by two nullable FKs, exactly one set.
CREATE TABLE qa_reactions (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint      NOT NULL,
    course_qa_id       bigint,
    course_qa_reply_id bigint,
    kind               text        NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_qa_reactions_target CHECK (num_nonnulls(course_qa_id, course_qa_reply_id) = 1),
    CONSTRAINT ck_qa_reactions_kind CHECK (kind IN ('like', 'dislike')),
    CONSTRAINT fk_qa_reactions_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_qa_reactions_course_qa_id FOREIGN KEY (course_qa_id)
        REFERENCES course_qas (id) ON DELETE CASCADE,
    CONSTRAINT fk_qa_reactions_course_qa_reply_id FOREIGN KEY (course_qa_reply_id)
        REFERENCES course_qa_replies (id) ON DELETE CASCADE
);
-- one reaction per user per item; target-leading so they also serve per-item like/dislike counts
CREATE UNIQUE INDEX uq_qa_reactions_course_qa_id_user_id ON qa_reactions (course_qa_id, user_id)
    WHERE course_qa_id IS NOT NULL;
CREATE UNIQUE INDEX uq_qa_reactions_course_qa_reply_id_user_id ON qa_reactions (course_qa_reply_id, user_id)
    WHERE course_qa_reply_id IS NOT NULL;
CREATE INDEX ix_qa_reactions_user_id ON qa_reactions (user_id);
CREATE TRIGGER trg_qa_reactions_updated_at BEFORE UPDATE ON qa_reactions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

