-- ---------------------------------------------------------------------------
-- reviews (one per learner per course)
-- ---------------------------------------------------------------------------
CREATE TABLE reviews (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL,
    course_id   bigint      NOT NULL,
    rating      smallint    NOT NULL,
    comment     text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_reviews_user_id_course_id UNIQUE (user_id, course_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_reviews_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_reviews_course_id FOREIGN KEY (course_id)
        REFERENCES courses (id) ON DELETE CASCADE
);
-- course page list (newest first) + AVG(rating)/COUNT via index-only scan
CREATE INDEX ix_reviews_course_id_created_at ON reviews (course_id, created_at DESC) INCLUDE (rating);
CREATE TRIGGER trg_reviews_updated_at BEFORE UPDATE ON reviews
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

