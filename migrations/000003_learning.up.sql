-- ---------------------------------------------------------------------------
-- lesson_progress (write-hot: one upsert per player heartbeat)
-- Narrow row, composite PK (no surrogate id, one less index to maintain),
-- `completed` derived from completed_at IS NOT NULL, SCORM runtime blob moved to
-- scorm_runtime_states. updated_at is deliberately NOT indexed so heartbeats stay HOT.
-- ---------------------------------------------------------------------------
CREATE TABLE lesson_progress (
    user_id          bigint      NOT NULL,
    lesson_id        bigint      NOT NULL,
    progress_percent smallint    NOT NULL DEFAULT 0,
    last_position    integer     NOT NULL DEFAULT 0,   -- seconds
    watched_seconds  integer     NOT NULL DEFAULT 0,
    completed_at     timestamptz,
    last_watched_at  timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_lesson_progress PRIMARY KEY (user_id, lesson_id),
    CONSTRAINT ck_lesson_progress_progress_percent CHECK (progress_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_lesson_progress_last_position CHECK (last_position >= 0),
    CONSTRAINT ck_lesson_progress_watched_seconds CHECK (watched_seconds >= 0),
    CONSTRAINT fk_lesson_progress_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_lesson_progress_lesson_id FOREIGN KEY (lesson_id)
        REFERENCES lessons (id) ON DELETE CASCADE
) WITH (fillfactor = 85);
CREATE INDEX ix_lesson_progress_lesson_id ON lesson_progress (lesson_id);
CREATE TRIGGER trg_lesson_progress_updated_at BEFORE UPDATE ON lesson_progress
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

