    weekday                 smallint    NOT NULL,  -- ISO: 1 = Monday .. 7 = Sunday
    start_time              time        NOT NULL,
    end_time                time        NOT NULL,
    room                    text,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
