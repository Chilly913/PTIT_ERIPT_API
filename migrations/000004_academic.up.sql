    room                    text,
    start_at                timestamptz   NOT NULL,
    duration_minutes        integer       NOT NULL,
    max_participants        integer,
    latitude                numeric(10,7),
    longitude               numeric(10,7),
    check_in_radius_meters  integer       NOT NULL DEFAULT 15,
    is_active               boolean       NOT NULL DEFAULT false,
    qr_enabled              boolean       NOT NULL DEFAULT true,
    qr_mode                 text          NOT NULL DEFAULT 'manual',
    qr_rotate_seconds       integer       NOT NULL DEFAULT 60,
    qr_token                text,
    qr_expires_at           timestamptz,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT fk_offline_sessions_lesson_id FOREIGN KEY (lesson_id)
        REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT fk_offline_sessions_class_section_id FOREIGN KEY (class_section_id)
        REFERENCES class_sections (id) ON DELETE CASCADE,
