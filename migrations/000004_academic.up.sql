-- =============================================================================
-- Cohorts (intake year groups)
-- =============================================================================

CREATE TABLE cohorts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id bigint      NOT NULL,
    program_id     bigint      NOT NULL,
    major_id       bigint,
    name           text        NOT NULL,
    code           citext      NOT NULL,
    start_year     smallint    NOT NULL,
    end_year       smallint,
    status         text        NOT NULL DEFAULT 'active',
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    -- program must belong to the same institution (also proves institution exists)
    CONSTRAINT fk_cohorts_program_id FOREIGN KEY (program_id, institution_id)
        REFERENCES programs (id, institution_id) ON DELETE CASCADE ON UPDATE CASCADE,
    -- major must belong to the cohort's program; on major delete only major_id is nulled
    CONSTRAINT fk_cohorts_major_id FOREIGN KEY (major_id, program_id)
        REFERENCES majors (id, program_id) ON DELETE SET NULL (major_id),
    CONSTRAINT uq_cohorts_program_id_code UNIQUE (program_id, code),
    CONSTRAINT uq_cohorts_id_program_id UNIQUE (id, program_id),
    CONSTRAINT ck_cohorts_start_year CHECK (start_year BETWEEN 1900 AND 2200),
    CONSTRAINT ck_cohorts_end_year CHECK (end_year IS NULL OR end_year >= start_year),
    CONSTRAINT ck_cohorts_status CHECK (status IN ('active', 'inactive', 'graduated'))
);
CREATE INDEX ix_cohorts_institution_id_status ON cohorts (institution_id, status);
CREATE INDEX ix_cohorts_major_id ON cohorts (major_id);
CREATE TRIGGER trg_cohorts_updated_at BEFORE UPDATE ON cohorts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- =============================================================================
-- Curricula (training frameworks) and their course slots
-- =============================================================================

CREATE TABLE curricula (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id        bigint      NOT NULL,
    major_id          bigint,
    specialization_id bigint,
    name              text        NOT NULL,
    code              citext      NOT NULL,
    effective_from    date,
    effective_to      date,
    is_active         boolean     NOT NULL DEFAULT true,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_curricula_program_id FOREIGN KEY (program_id)
        REFERENCES programs (id) ON DELETE CASCADE,
    CONSTRAINT fk_curricula_major_id FOREIGN KEY (major_id, program_id)
        REFERENCES majors (id, program_id) ON DELETE SET NULL (major_id),
    CONSTRAINT fk_curricula_specialization_id FOREIGN KEY (specialization_id, major_id)
        REFERENCES specializations (id, major_id) ON DELETE SET NULL (specialization_id),
    CONSTRAINT uq_curricula_program_id_code UNIQUE (program_id, code),
    CONSTRAINT uq_curricula_id_program_id UNIQUE (id, program_id),
    -- a specialization only makes sense under a major
    CONSTRAINT ck_curricula_specialization_requires_major CHECK (specialization_id IS NULL OR major_id IS NOT NULL),
    CONSTRAINT ck_curricula_effective_range CHECK (
        effective_from IS NULL OR effective_to IS NULL OR effective_from <= effective_to)
);
CREATE INDEX ix_curricula_major_id_specialization_id ON curricula (major_id, specialization_id);
CREATE INDEX ix_curricula_specialization_id ON curricula (specialization_id);
CREATE TRIGGER trg_curricula_updated_at BEFORE UPDATE ON curricula
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

