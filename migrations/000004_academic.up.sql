-- 000004_academic: academic structure (calendar, programs, curricula, outcomes,
-- administrative classes, class sections, schedules, offline sessions/attendance).
-- References: 000002_identity (institutions, units, users),
--             000003_learning (courses, lessons, course_learning_outcomes).
-- Design notes: docs/db/04_academic.md

-- =============================================================================
-- Academic calendar
-- =============================================================================

CREATE TABLE academic_years (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id bigint      NOT NULL,
    name           text        NOT NULL,
    start_date     date        NOT NULL,
    end_date       date        NOT NULL,
    is_current     boolean     NOT NULL DEFAULT false,
    status         text        NOT NULL DEFAULT 'planned',
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_academic_years_institution_id FOREIGN KEY (institution_id)
        REFERENCES institutions (id) ON DELETE RESTRICT,
    CONSTRAINT uq_academic_years_institution_id_name UNIQUE (institution_id, name),
    CONSTRAINT ck_academic_years_dates CHECK (start_date < end_date),
    CONSTRAINT ck_academic_years_status CHECK (status IN ('planned', 'active', 'inactive', 'completed'))
);
-- At most one current academic year per institution.
CREATE UNIQUE INDEX uq_academic_years_institution_id_current
    ON academic_years (institution_id) WHERE is_current;
CREATE TRIGGER trg_academic_years_updated_at BEFORE UPDATE ON academic_years
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE terms (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year_id    bigint      NOT NULL,
    name                text        NOT NULL,
    code                citext      NOT NULL,
    start_date          date        NOT NULL,
    end_date            date        NOT NULL,
    enrollment_start_at timestamptz,
    enrollment_end_at   timestamptz,
    exam_start_at       timestamptz,
    exam_end_at         timestamptz,
    is_current          boolean     NOT NULL DEFAULT false,
    status              text        NOT NULL DEFAULT 'planned',
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_terms_academic_year_id FOREIGN KEY (academic_year_id)
        REFERENCES academic_years (id) ON DELETE CASCADE,
    CONSTRAINT uq_terms_academic_year_id_code UNIQUE (academic_year_id, code),
    CONSTRAINT ck_terms_dates CHECK (start_date < end_date),
    CONSTRAINT ck_terms_enrollment_window CHECK (
        enrollment_start_at IS NULL OR enrollment_end_at IS NULL OR enrollment_start_at <= enrollment_end_at),
    CONSTRAINT ck_terms_exam_window CHECK (
        exam_start_at IS NULL OR exam_end_at IS NULL OR exam_start_at <= exam_end_at),
    CONSTRAINT ck_terms_status CHECK (status IN ('planned', 'upcoming', 'ongoing', 'active', 'completed'))
);
-- At most one current term per academic year.
CREATE UNIQUE INDEX uq_terms_academic_year_id_current
    ON terms (academic_year_id) WHERE is_current;
-- Term::operational(): start_date <= today <= end_date ORDER BY start_date DESC.
CREATE INDEX ix_terms_start_date_end_date ON terms (start_date, end_date);
CREATE TRIGGER trg_terms_updated_at BEFORE UPDATE ON terms
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

