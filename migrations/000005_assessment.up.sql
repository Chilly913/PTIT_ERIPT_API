CREATE TRIGGER trg_question_banks_updated_at BEFORE UPDATE ON question_banks
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- A "set" of questions inside a bank (or a course-level set when the bank is NULL).
-- Used for UI grouping and as a filter in quiz random rules (settings.random_rules[].group_id).
CREATE TABLE question_groups (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id        bigint      NOT NULL,
    question_bank_id bigint,
    name             text        NOT NULL,
    description      text,
    position         integer     NOT NULL DEFAULT 0,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_question_groups_course_id FOREIGN KEY (course_id)
        REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_question_groups_question_bank_id FOREIGN KEY (question_bank_id)
        REFERENCES question_banks (id) ON DELETE SET NULL,
    CONSTRAINT ck_question_groups_name CHECK (char_length(name) BETWEEN 1 AND 255),
    CONSTRAINT ck_question_groups_position CHECK (position >= 0)
);
CREATE INDEX ix_question_groups_course_id_position ON question_groups (course_id, position);
CREATE INDEX ix_question_groups_question_bank_id_position ON question_groups (question_bank_id, position);
CREATE TRIGGER trg_question_groups_updated_at BEFORE UPDATE ON question_groups
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE questions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              citext       NOT NULL,
    course_id         bigint       NOT NULL,
    question_bank_id  bigint,
    question_group_id bigint,
    type              text         NOT NULL DEFAULT 'single_choice',
    content           text         NOT NULL,
    difficulty        smallint     NOT NULL DEFAULT 1,
    default_score     numeric(6,2) NOT NULL DEFAULT 1.00,
    explanation       text,
    feedback          text,
    general_feedback  text,
    metadata          jsonb,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_questions_code UNIQUE (code),
    CONSTRAINT fk_questions_course_id FOREIGN KEY (course_id)
        REFERENCES courses (id) ON DELETE CASCADE,
    CONSTRAINT fk_questions_question_bank_id FOREIGN KEY (question_bank_id)
        REFERENCES question_banks (id) ON DELETE SET NULL,
    CONSTRAINT fk_questions_question_group_id FOREIGN KEY (question_group_id)
        REFERENCES question_groups (id) ON DELETE SET NULL,
    CONSTRAINT ck_questions_code CHECK (char_length(code) BETWEEN 1 AND 50),
    CONSTRAINT ck_questions_type CHECK (type IN (
        'single_choice', 'multiple_choice', 'true_false', 'essay',
        'matching', 'ordering', 'short_answer', 'numerical')),
    CONSTRAINT ck_questions_difficulty CHECK (difficulty BETWEEN 1 AND 5),
    CONSTRAINT ck_questions_default_score CHECK (default_score >= 0),
    CONSTRAINT ck_questions_metadata CHECK (metadata IS NULL OR jsonb_typeof(metadata) = 'object')
);
CREATE INDEX ix_questions_course_id ON questions (course_id);
-- random rules: WHERE question_bank_id = ? [AND difficulty = ?]; bank difficulty distribution
CREATE INDEX ix_questions_question_bank_id_difficulty ON questions (question_bank_id, difficulty);
CREATE INDEX ix_questions_question_group_id ON questions (question_group_id);
CREATE TRIGGER trg_questions_updated_at BEFORE UPDATE ON questions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Options / reference answers of a question (legacy table `answers`).
-- Correct-answer model per question type:
--   single_choice/true_false: exactly one row is_correct
--   multiple_choice: set of rows is_correct (exact set match)
--   short_answer: rows with is_correct hold accepted texts (case-insensitive)
--   numerical: the is_correct row's content is the value, tolerance in questions.metadata
--   matching: content (left) must be matched with sub_content (right)
--   ordering: correct_position is the expected position
--   essay: no automatic grading
CREATE TABLE question_answers (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id      bigint      NOT NULL,
    position         integer     NOT NULL DEFAULT 0,
    content          text        NOT NULL,
    sub_content      text,
    correct_position integer,
    is_correct       boolean     NOT NULL DEFAULT false,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_question_answers_question_id FOREIGN KEY (question_id)
        REFERENCES questions (id) ON DELETE CASCADE,
    CONSTRAINT uq_question_answers_question_id_position UNIQUE (question_id, position),
    CONSTRAINT ck_question_answers_position CHECK (position >= 0),
    CONSTRAINT ck_question_answers_correct_position CHECK (correct_position IS NULL OR correct_position >= 0)
);
CREATE TRIGGER trg_question_answers_updated_at BEFORE UPDATE ON question_answers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

