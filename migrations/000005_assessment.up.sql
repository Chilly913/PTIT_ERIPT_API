    CONSTRAINT ck_quiz_attempts_force_stop_reason CHECK (force_stop_reason IS NULL OR status = 'force_stopped'),
    CONSTRAINT ck_quiz_attempts_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_quiz_attempts_paused_duration CHECK (paused_duration >= 0),
    CONSTRAINT ck_quiz_attempts_time_extensions CHECK (time_extensions >= 0),
    CONSTRAINT ck_quiz_attempts_answers CHECK (answers IS NULL OR jsonb_typeof(answers) = 'object')
