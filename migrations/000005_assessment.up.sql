-- Upper bound of a score is the component's max_score (cross-table, so a trigger).
CREATE FUNCTION grade_entries_check_score() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_max numeric;
BEGIN
    IF NEW.score IS NOT NULL THEN
        SELECT max_score INTO v_max FROM grade_components WHERE id = NEW.grade_component_id;
        IF v_max IS NOT NULL AND NEW.score > v_max THEN
            RAISE EXCEPTION 'grade_entries.score % exceeds max_score % of component %',
                NEW.score, v_max, NEW.grade_component_id
                USING ERRCODE = 'check_violation', CONSTRAINT = 'ck_grade_entries_score_max';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_grade_entries_check_score BEFORE INSERT OR UPDATE OF score, grade_component_id
    ON grade_entries FOR EACH ROW EXECUTE FUNCTION grade_entries_check_score();
