-- ---------------------------------------------------------------------------
-- orders (payment header) + order_items (what was purchased)
-- ---------------------------------------------------------------------------
CREATE TABLE orders (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint        NOT NULL,
    status              text          NOT NULL DEFAULT 'pending',
    original_amount     numeric(14,2) NOT NULL DEFAULT 0,  -- sum of item list prices
    discount_amount     numeric(14,2) NOT NULL DEFAULT 0,
    amount              numeric(14,2) NOT NULL,            -- payable total sent to the gateway
    user_voucher_id     bigint,
    payment_method      text          NOT NULL DEFAULT 'payos',
    provider_order_code bigint,       -- PayOS orderCode (positive int <= 2^53-1); webhook lookup key
    payment_link_id     text,         -- PayOS paymentLinkId of the current checkout link
    provider_txn_ref    text,         -- gateway transaction reference reported on success
    gateway_response    jsonb,
    paid_at             timestamptz,
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ck_orders_status CHECK (status IN ('pending', 'paid', 'failed', 'cancelled', 'refunded')),
    CONSTRAINT ck_orders_payment_method CHECK (payment_method IN ('payos', 'momo', 'zalopay', 'bank_transfer', 'free')),
    CONSTRAINT ck_orders_amounts CHECK (
        original_amount >= 0 AND discount_amount >= 0 AND amount >= 0
        AND amount = original_amount - discount_amount),
    CONSTRAINT ck_orders_free_is_zero CHECK (payment_method <> 'free' OR amount = 0),
    CONSTRAINT ck_orders_paid_at CHECK (status NOT IN ('paid', 'refunded') OR paid_at IS NOT NULL),
    CONSTRAINT ck_orders_provider_order_code CHECK (
        provider_order_code IS NULL OR provider_order_code BETWEEN 1 AND 9007199254740991),
    CONSTRAINT uq_orders_provider_order_code UNIQUE (payment_method, provider_order_code),
    CONSTRAINT uq_orders_payment_link_id UNIQUE (payment_method, payment_link_id),
    CONSTRAINT uq_orders_provider_txn_ref UNIQUE (payment_method, provider_txn_ref),
    CONSTRAINT fk_orders_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_user_voucher_id FOREIGN KEY (user_voucher_id)
        REFERENCES user_vouchers (id) ON DELETE SET NULL
);
-- user order history: WHERE user_id ORDER BY created_at DESC
CREATE INDEX ix_orders_user_id_created_at ON orders (user_id, created_at DESC);
-- admin list: optional status filter, ORDER BY created_at DESC
CREATE INDEX ix_orders_status_created_at ON orders (status, created_at DESC);
-- revenue dashboards: status = 'paid', grouped by month
CREATE INDEX ix_orders_paid_at ON orders (paid_at) WHERE status = 'paid';
-- a user voucher can be locked by at most one pending/paid order (replaces the
-- "locked voucher" query in CheckoutService and makes double-spend impossible)
CREATE UNIQUE INDEX uq_orders_user_voucher_id_active ON orders (user_voucher_id)
    WHERE user_voucher_id IS NOT NULL AND status IN ('pending', 'paid');
CREATE INDEX ix_orders_user_voucher_id ON orders (user_voucher_id) WHERE user_voucher_id IS NOT NULL;
CREATE TRIGGER trg_orders_updated_at BEFORE UPDATE ON orders
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

