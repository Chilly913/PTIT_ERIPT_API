    WHERE user_voucher_id IS NOT NULL;

-- Ledger rows are immutable. UPDATE is always rejected; DELETE is rejected unless it
-- is cascaded from a parent row (users delete / user_vouchers SET NULL run as RI triggers,
-- so pg_trigger_depth() > 1 there).
CREATE FUNCTION point_transactions_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        -- allow only the FK SET NULL performed by the RI trigger on user_vouchers delete
        IF pg_trigger_depth() > 1
           AND NEW.user_voucher_id IS NULL
           AND (to_jsonb(NEW) - 'user_voucher_id') = (to_jsonb(OLD) - 'user_voucher_id') THEN
            RETURN NEW;
        END IF;
        RAISE EXCEPTION 'point_transactions is append-only (UPDATE of id % rejected)', OLD.id
            USING ERRCODE = 'restrict_violation';
    END IF;
    IF pg_trigger_depth() > 1 THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'point_transactions is append-only (DELETE of id % rejected)', OLD.id
        USING ERRCODE = 'restrict_violation';
END;
$$;
CREATE TRIGGER trg_point_transactions_append_only BEFORE UPDATE OR DELETE ON point_transactions
    FOR EACH ROW EXECUTE FUNCTION point_transactions_append_only();

-- Reconciliation view: authoritative balance derived from the ledger.
CREATE VIEW user_point_balances AS
SELECT user_id,
       SUM(amount)::bigint                                    AS balance,
       COALESCE(SUM(amount) FILTER (WHERE type = 'earn'), 0)::bigint AS total_earned,
       COALESCE(-SUM(amount) FILTER (WHERE type = 'redeem'), 0)::bigint AS total_redeemed,
       MAX(created_at)                                        AS last_transaction_at
FROM point_transactions
GROUP BY user_id;

