CREATE TABLE vouchers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text          NOT NULL,
    description    text,
    type           text          NOT NULL,
    discount_value numeric(14,2),            -- percent (0-100) for discount_percent, VND for discount_fixed
    points_cost    bigint        NOT NULL,
    total_quantity integer,                  -- NULL = unlimited
    redeemed_count integer       NOT NULL DEFAULT 0,
    image_path     text,
    is_active      boolean       NOT NULL DEFAULT true,
    starts_at      timestamptz,              -- NULL = available immediately
    expires_at     timestamptz,              -- NULL = never expires
    course_id      bigint,                   -- NULL = applies to any course
    created_at     timestamptz   NOT NULL DEFAULT now(),
    updated_at     timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT ck_vouchers_name CHECK (char_length(name) BETWEEN 1 AND 100),
    CONSTRAINT ck_vouchers_type CHECK (type IN ('discount_percent', 'discount_fixed', 'free_course', 'physical_gift', 'ai_quota')),
    CONSTRAINT ck_vouchers_discount_value CHECK (
        discount_value IS NULL OR discount_value >= 0),
    CONSTRAINT ck_vouchers_discount_value_required CHECK (
        type NOT IN ('discount_percent', 'discount_fixed') OR discount_value IS NOT NULL),
    CONSTRAINT ck_vouchers_discount_percent_range CHECK (
        type <> 'discount_percent' OR discount_value <= 100),
    CONSTRAINT ck_vouchers_points_cost CHECK (points_cost >= 1),
    CONSTRAINT ck_vouchers_total_quantity CHECK (total_quantity IS NULL OR total_quantity >= 1),
    CONSTRAINT ck_vouchers_redeemed_count CHECK (
        redeemed_count >= 0 AND (total_quantity IS NULL OR redeemed_count <= total_quantity)),
    CONSTRAINT ck_vouchers_validity_window CHECK (
        starts_at IS NULL OR expires_at IS NULL OR starts_at < expires_at),
    CONSTRAINT fk_vouchers_course_id FOREIGN KEY (course_id)
        REFERENCES courses (id) ON DELETE SET NULL
