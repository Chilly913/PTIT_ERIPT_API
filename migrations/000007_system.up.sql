-- 000007_system: notifications, news, site settings, AI settings/logs, surveys.
-- See docs/db/07_system.md for design notes and the legacy -> new mapping.

-- In-app notifications (custom table, not Laravel's polymorphic notifications).
-- One row per recipient; broadcasts fan out.
CREATE TABLE notifications (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id    bigint      NOT NULL,
    type       text        NOT NULL,
    title      text        NOT NULL,
    message    text        NOT NULL,
    link       text,
    read_at    timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_notifications PRIMARY KEY (id),
    CONSTRAINT fk_notifications_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_type CHECK (type IN (
        'announcement', 'news', 'enrollment', 'academic_warning',
        'course_approved', 'course_rejected',
        'exam_paused', 'exam_resumed', 'exam_force_stopped', 'exam_time_extended', 'exam_violation')),
    CONSTRAINT ck_notifications_title CHECK (char_length(title) <= 255),
    CONSTRAINT ck_notifications_message CHECK (char_length(message) <= 5000),
    CONSTRAINT ck_notifications_link CHECK (char_length(link) <= 500)
);
-- list newest-first per user (keyset/offset on id DESC == created_at DESC)
CREATE INDEX ix_notifications_user_id_id ON notifications (user_id, id DESC);
-- unread badge count and "mark all read" touch only unread rows
CREATE INDEX ix_notifications_user_id_unread ON notifications (user_id) WHERE read_at IS NULL;

CREATE TABLE news_posts (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    author_id        bigint,
    title            text        NOT NULL,
    slug             text        NOT NULL,
    excerpt          text,
    content          text,
    cover_image_path text,                   -- object key
    status           text        NOT NULL DEFAULT 'draft',
    is_featured      boolean     NOT NULL DEFAULT false,
    published_at     timestamptz,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_news_posts PRIMARY KEY (id),
    CONSTRAINT uq_news_posts_slug UNIQUE (slug),
    CONSTRAINT fk_news_posts_author_id FOREIGN KEY (author_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_news_posts_status CHECK (status IN ('draft', 'published')),
    CONSTRAINT ck_news_posts_title CHECK (char_length(title) <= 255),
    CONSTRAINT ck_news_posts_excerpt CHECK (char_length(excerpt) <= 500),
    CONSTRAINT ck_news_posts_published CHECK (status <> 'published' OR published_at IS NOT NULL)
);
CREATE INDEX ix_news_posts_author_id ON news_posts (author_id);
-- public feed: status = 'published' AND published_at <= now() ORDER BY published_at DESC
CREATE INDEX ix_news_posts_published_at ON news_posts (published_at DESC) WHERE status = 'published';
-- admin search: title ILIKE / excerpt ILIKE
CREATE INDEX ix_news_posts_title_trgm ON news_posts USING gin (title gin_trgm_ops);
CREATE INDEX ix_news_posts_excerpt_trgm ON news_posts USING gin (excerpt gin_trgm_ops);
CREATE TRIGGER trg_news_posts_updated_at BEFORE UPDATE ON news_posts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Key/value site configuration. Secrets (smtp_password) go to value_encrypted,
-- encrypted by the Go app with its own key; everything else is plain text in value.
CREATE TABLE site_settings (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    key             text        NOT NULL,
    value           text,
    value_encrypted bytea,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_site_settings PRIMARY KEY (id),
    CONSTRAINT uq_site_settings_key UNIQUE (key),
    CONSTRAINT ck_site_settings_key CHECK (key ~ '^[a-z][a-z0-9_]{0,99}$'),
    CONSTRAINT ck_site_settings_value CHECK (value IS NULL OR value_encrypted IS NULL)
);
CREATE TRIGGER trg_site_settings_updated_at BEFORE UPDATE ON site_settings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Singleton row with the AI provider configuration.
CREATE TABLE ai_settings (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY,
    provider                text        NOT NULL DEFAULT 'gemini',
    model                   text        NOT NULL DEFAULT 'gemini-2.5-flash',
    api_key_encrypted       bytea,       -- encrypted by the Go app (own key); never returned by the API
    monthly_token_quota     bigint      NOT NULL DEFAULT 1000000,
    tokens_used             bigint      NOT NULL DEFAULT 0,
    max_requests_per_minute integer     NOT NULL DEFAULT 60,
    is_active               boolean     NOT NULL DEFAULT true,
    quota_reset_at          timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_ai_settings PRIMARY KEY (id),
    CONSTRAINT ck_ai_settings_provider CHECK (provider IN ('chatgpt', 'gemini', 'claude', 'openrouter', 'ollama')),
    CONSTRAINT ck_ai_settings_model CHECK (char_length(model) <= 100),
    CONSTRAINT ck_ai_settings_monthly_token_quota CHECK (monthly_token_quota >= 0),
    CONSTRAINT ck_ai_settings_tokens_used CHECK (tokens_used >= 0),
    CONSTRAINT ck_ai_settings_max_requests_per_minute CHECK (max_requests_per_minute BETWEEN 1 AND 1000)
);
CREATE UNIQUE INDEX uq_ai_settings_singleton ON ai_settings ((true));
CREATE TRIGGER trg_ai_settings_updated_at BEFORE UPDATE ON ai_settings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Append-only AI call log, bulk-inserted from Redis every ~15 s. No updated_at.
CREATE TABLE ai_request_logs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id          bigint,
    endpoint         text        NOT NULL,
    provider         text        NOT NULL,
    model            text        NOT NULL,
    status           text        NOT NULL,
    tokens_used      integer     NOT NULL DEFAULT 0,
    response_time_ms integer     NOT NULL DEFAULT 0,
    error_message    text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_ai_request_logs PRIMARY KEY (id),
    CONSTRAINT fk_ai_request_logs_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_ai_request_logs_status CHECK (status IN ('success', 'error')),
    CONSTRAINT ck_ai_request_logs_tokens_used CHECK (tokens_used >= 0),
    CONSTRAINT ck_ai_request_logs_response_time_ms CHECK (response_time_ms >= 0)
);
-- recent logs (ORDER BY created_at DESC LIMIT n) and the 14-day daily chart
CREATE INDEX ix_ai_request_logs_created_at ON ai_request_logs (created_at);
-- per-user lookups and FK ON DELETE SET NULL; anonymous (guest) rows are not indexed
CREATE INDEX ix_ai_request_logs_user_id ON ai_request_logs (user_id) WHERE user_id IS NOT NULL;

-- One experience-survey response per user (resubmission overwrites).
CREATE TABLE experience_survey_responses (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id        bigint      NOT NULL,
    survey_version text        NOT NULL DEFAULT 'v1',
    answers        jsonb       NOT NULL,
    submitted_at   timestamptz NOT NULL DEFAULT now(),
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_experience_survey_responses PRIMARY KEY (id),
    CONSTRAINT uq_experience_survey_responses_user_id UNIQUE (user_id),
    CONSTRAINT fk_experience_survey_responses_user_id FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_experience_survey_responses_survey_version CHECK (char_length(survey_version) <= 20),
    CONSTRAINT ck_experience_survey_responses_answers CHECK (jsonb_typeof(answers) = 'object')
);
CREATE INDEX ix_experience_survey_responses_submitted_at ON experience_survey_responses (submitted_at DESC);
CREATE TRIGGER trg_experience_survey_responses_updated_at BEFORE UPDATE ON experience_survey_responses
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
