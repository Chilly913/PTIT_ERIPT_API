-- 000093_partners: cooperation partners shown on the public site (logo wall).
-- logo_path is either an object key or a site-relative asset path starting with "/".
CREATE TABLE partners (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    name        text        NOT NULL,
    logo_path   text        NOT NULL,
    website_url text,
    sort_order  integer     NOT NULL DEFAULT 0,
    is_active   boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_partners PRIMARY KEY (id),
    CONSTRAINT uq_partners_name UNIQUE (name),
    CONSTRAINT ck_partners_name CHECK (char_length(name) <= 150),
    CONSTRAINT ck_partners_website_url CHECK (website_url IS NULL OR website_url ~ '^https?://')
);
-- public list: is_active ORDER BY sort_order, id
CREATE INDEX ix_partners_sort ON partners (sort_order, id) WHERE is_active;
CREATE TRIGGER trg_partners_updated_at BEFORE UPDATE ON partners
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
