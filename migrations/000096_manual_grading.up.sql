-- 000096_manual_grading: grading of answers that need a human (essay, file upload) and the files learners attach.
--   grading_status  none = fully auto-graded, pending = waiting for a grader, graded = every manual question has a score
--   grading         {"questions": {"<question_id>": {"score": 1.5, "comment": "..."}}, "overall_feedback": "..."}
--   attempt_files   files attached to a file_upload answer; stored under UPLOAD_DIR/private/answers/<attempt_id>/ (never public)
ALTER TABLE quiz_attempts
    ADD COLUMN grading_status text NOT NULL DEFAULT 'none',
    ADD COLUMN grading        jsonb,
    ADD COLUMN graded_by      bigint,
    ADD COLUMN graded_at      timestamptz,
    ADD CONSTRAINT ck_quiz_attempts_grading_status CHECK (grading_status IN ('none', 'pending', 'graded')),
    ADD CONSTRAINT ck_quiz_attempts_grading CHECK (grading IS NULL OR jsonb_typeof(grading) = 'object'),
    ADD CONSTRAINT fk_quiz_attempts_graded_by FOREIGN KEY (graded_by) REFERENCES users (id) ON DELETE SET NULL;
CREATE INDEX ix_quiz_attempts_grading_pending ON quiz_attempts (quiz_id) WHERE grading_status = 'pending';
CREATE INDEX ix_quiz_attempts_graded_by ON quiz_attempts (graded_by) WHERE graded_by IS NOT NULL;

CREATE TABLE attempt_files (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id    bigint      NOT NULL,
    question_id   bigint      NOT NULL,
    original_name text        NOT NULL,
    stored_path   text        NOT NULL,   -- relative to UPLOAD_DIR
    size_bytes    bigint      NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_attempt_files_attempt_id FOREIGN KEY (attempt_id) REFERENCES quiz_attempts (id) ON DELETE CASCADE,
    CONSTRAINT fk_attempt_files_question_id FOREIGN KEY (question_id) REFERENCES questions (id) ON DELETE CASCADE,
    CONSTRAINT ck_attempt_files_original_name CHECK (char_length(original_name) BETWEEN 1 AND 255),
    CONSTRAINT ck_attempt_files_size_bytes CHECK (size_bytes >= 0)
);
CREATE INDEX ix_attempt_files_attempt_id_question_id ON attempt_files (attempt_id, question_id);
CREATE INDEX ix_attempt_files_question_id ON attempt_files (question_id);
CREATE TRIGGER trg_attempt_files_updated_at BEFORE UPDATE ON attempt_files
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
